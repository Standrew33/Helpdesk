namespace Helpdesk.Web.Features.Attachments;

/// <summary>Keeps attachments in a local folder. Used for development and tests when no Blob Storage is configured.</summary>
public sealed class LocalAttachmentStore : IAttachmentStore
{
    private readonly string _root;

    public LocalAttachmentStore(string root)
    {
        _root = Path.GetFullPath(root);
        Directory.CreateDirectory(_root);
    }

    public async Task SaveAsync(string name, Stream content, string contentType, CancellationToken ct = default)
    {
        await using var file = File.Create(PathFor(name));
        await content.CopyToAsync(file, ct);
    }

    public Task<Stream?> OpenReadAsync(string name, CancellationToken ct = default)
    {
        var path = PathFor(name);
        return Task.FromResult<Stream?>(File.Exists(path) ? File.OpenRead(path) : null);
    }

    public Task DeleteAsync(string name, CancellationToken ct = default)
    {
        File.Delete(PathFor(name));
        return Task.CompletedTask;
    }

    private string PathFor(string name)
    {
        // Stored names are generated by the application; refuse anything that is not a plain file name.
        if (name != Path.GetFileName(name) || name.Length == 0)
        {
            throw new ArgumentException("Invalid stored file name.", nameof(name));
        }

        return Path.Combine(_root, name);
    }
}
